def run_command(args: list[str]) -> tuple[int, str, str]:
    proc = subprocess.run(args, cwd=ROOT, text=True, capture_output=True, check=False)
    return proc.returncode, proc.stdout, proc.stderr


def run_gates(activity: dict[str, Any], database: dict[str, Any], mechanism: dict[str, Any]) -> bool:
    manifest = REPORTS / f"{PAPER_ID}.complete_message_test_manifest.json"
    semantic_path = REPORTS / f"{PAPER_ID}.semantic_gate.json"
    publication_path = REPORTS / f"{PAPER_ID}.publication_quality.json"

    semantic_code, semantic_out, semantic_err = run_command(
        [
            sys.executable,
            ".codex/skills/paper-batch-orchestrator/scripts/semantic_three_layer_gate.py",
            "--root",
            ".",
            "--manifest",
            str(manifest),
            "--json",
        ]
    )
    try:
        semantic = json.loads(semantic_out)
    except json.JSONDecodeError as exc:
        raise RuntimeError(f"semantic gate emitted invalid JSON: {exc}\nstdout={semantic_out}\nstderr={semantic_err}") from exc
    write_json(semantic_path, semantic)

    publication_code, publication_out, publication_err = run_command(
        [
            sys.executable,
            ".codex/skills/paper-batch-orchestrator/scripts/check_three_layer_publication_quality.py",
            "--root",
            ".",
            "--manifest",
            str(manifest),
            "--json-out",
            str(publication_path),
        ]
    )
    if not publication_path.exists():
        raise RuntimeError(f"publication gate failed to write {publication_path}\nstdout={publication_out}\nstderr={publication_err}")
    publication = read_json(publication_path)

    gates_ready = (
        semantic_code == 0
        and publication_code == 0
        and int(semantic.get("publication_grade_pass_count") or 0) == 1
        and int(semantic.get("publication_grade_fail_count") or 0) == 0
        and publication.get("publication_grade_pass") is True
    )
    generated_at = now_iso()
    gate_evidence = {
        "semantic_report": str(semantic_path),
        "semantic_returncode": semantic_code,
        "semantic_publication_grade_pass_count": semantic.get("publication_grade_pass_count"),
        "semantic_publication_grade_fail_count": semantic.get("publication_grade_fail_count"),
        "semantic_issue_count": (semantic.get("results") or [{}])[0].get("issue_count"),
        "publication_report": str(publication_path),
        "publication_returncode": publication_code,
        "publication_grade_pass": publication.get("publication_grade_pass"),
        "publication_risk_counts": publication.get("risk_counts"),
    }

    if not gates_ready:
        target = {
            "ticket_id": f"{TICKET_ID}-post-gate",
            "paper_id": PAPER_ID,
            "worker": "worker-6",
            "owner_worker": "worker-6",
            "target_queue": "adjudication",
            "layer": "review",
            "failure_code": "strict_gate_failure_after_worker246_repair",
            "omission_code": "strict_gate_failure_after_source_review",
            "artifact_path": f"papers/{PAPER_ID}/final/review_report.json",
            "source_evidence_to_check": SOURCE_PATHS_CHECKED,
            "required_action": "Resolve the strict gate failures without marking the paper accepted.",
            "created_at": generated_at,
            "severity": "blocking",
            "blocks": ["publication_grade_ready", "final_approval"],
        }
        qc_reasons = [
            {
                "code": "strict_gate_failure_after_worker246_repair",
                "owner_worker": "worker-6",
                "severity": "blocking",
                "reason": "Strict semantic/publication gate still failed after bounded worker-2/4/6 source review.",
                "semantic_issues": (semantic.get("results") or [{}])[0].get("issues", [])[:8],
                "publication_risk_counts": publication.get("risk_counts"),
            }
        ]
        review = read_json(PAPER / "final" / "review_report.json")
        review.update({"review_status": "needs_targeted_rework", "publication_grade": False, "qc_failure_reasons": qc_reasons, "rework_targets": [target]})
        for path in [PAPER / "final" / "review_report.json", PACKET / "final" / "review_report.json", PACKET / "analysis" / "adjudication_report.json"]:
            write_json(path, review)
        write_json(
            PAPER / "work" / "review" / "quality_feedback.json",
            {
                "paper_id": PAPER_ID,
                "generated_at": generated_at,
                "status": "qc_failed_after_worker246_repair",
                "issue_count": len(qc_reasons),
                "qc_failure_reasons": qc_reasons,
                "rework_targets": [target],
                "rework_context_packet_required": True,
                "unrecoverable_material_gaps": [],
            },
        )
        append_jsonl(PACKET / "rework" / "rework_requests.jsonl", target)

    update_status_files(generated_at, gates_ready, gate_evidence)
    append_jsonl(PACKET / "rework" / "rework_responses.jsonl", rework_response(generated_at, gate_evidence, gates_ready))
    write_complete_report(generated_at, gates_ready, gate_evidence, activity, database, mechanism)
    print(json.dumps({"ok": True, "gates_ready": gates_ready, "gate_evidence": gate_evidence}, ensure_ascii=False, indent=2))
    return gates_ready


